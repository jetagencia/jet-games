export const lang = () => { try { return window.JETIdioma && window.JETIdioma.get() === 'en' ? 'en' : 'es'; } catch { return 'es'; } };
export const isEn = () => lang() === 'en';
// texto en línea con sus dos idiomas: L('Hola', 'Hello')
export const L = (es, en) => (lang() === 'en' ? en : es);
// texto que se guarda (registro del rancho): se guardan los dos y se elige al mostrarlo
export const bi = (es, en) => ({ es, en });
export const tx = (v) => (v && typeof v === 'object' ? (lang() === 'en' ? v.en : v.es) ?? v.es ?? '' : v ?? '');

const nf = (d) => new Intl.NumberFormat(lang() === 'en' ? 'en' : 'es', { minimumFractionDigits: d, maximumFractionDigits: d });
// número con decimales en el formato del idioma (1,10 en español, 1.10 en inglés)
export const dec = (v, d = 2) => nf(d).format(v);
export const fmt = {
  secLive: (s) => nf(1).format(Math.max(0, s)),                // 12,4 durante el juego
  secFinal: (s) => nf(2).format(Math.max(0, s)),               // 12,43 en el resultado
  meters: (m) => nf(2).format(m) + ' m',                       // 1,10 m
  points: (n) => (lang() === 'en' ? `${n} ${n === 1 ? 'fault' : 'faults'}` : `${n} ${n === 1 ? 'punto' : 'puntos'}`),
  pts: (n) => (lang() === 'en' ? `${n} ${n === 1 ? 'flt' : 'flts'}` : `${n} ${n === 1 ? 'pt' : 'pts'}`),   // solo donde falta espacio
};

